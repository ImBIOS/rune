#!/usr/bin/env bun
// Bundles the knobs page that debug runtimes serve from their own port into the embedded copy.
import { resolve } from "node:path"

const here = import.meta.dir
const output = resolve(here, "../../crates/rune/src/dev/panel.js")
// Files whose bytes the stamp covers. `cargo test` recomputes it from the same files.
const sources = ["index.ts", "package.json"]

export async function bundle(options: { minify?: boolean, conditions?: string[] } = {}) {
  const built = await Bun.build({
    entrypoints: [resolve(here, "index.ts")],
    target: "browser",
    conditions: options.conditions,
    minify: options.minify,
    external: ["@pierre/diffs"],
  })
  if (!built.success) throw new AggregateError(built.logs, "Could not bundle the knobs remote page")
  return built.outputs[0]!.text()
}

// FNV-1a 64 over each source followed by a zero byte.
export async function stamp() {
  let hash = 0xcbf29ce484222325n
  for (const name of sources) {
    for (const byte of [...await Bun.file(resolve(here, name)).bytes(), 0]) {
      hash = ((hash ^ BigInt(byte)) * 0x100000001b3n) & 0xffffffffffffffffn
    }
  }
  return hash.toString(16).padStart(16, "0")
}

if (import.meta.main) {
  const page = `// Generated by scripts/dev-panel/build.ts; do not edit. source ${await stamp()}\n${await bundle({ minify: true })}`
  await Bun.write(output, page)
  console.log(`Wrote ${output} (${page.length} bytes)`)
}
